import {
  APP_NAME,
  formatDuration,
  hoursAndMinutes,
  keyShort,
  type Language,
  type MusicalKey,
  playedDuration,
  type SetlistExportFormat,
  setlistDuration,
} from "@coverband/shared";

/**
 * What an exported setlist shows (brief 030), the same for every format: texts already written in
 * the requester's language and time zone, so a renderer only lays them out.
 */
export type ExportDocument = {
  language: Language;
  title: string;
  /** How many songs it has: "12 songs". */
  songCount: string;
  /** "1 h 52 min (2 songs without a duration)", or null for a setlist without songs. */
  duration: string | null;
  band: string;
  /** The setlist's last change, as a date. */
  date: string;
  /** The band's full-size logo in the bucket, or null. */
  logoKey: string | null;
  parts: ExportPart[];
};

export type ExportPart = { name: string; duration: string | null; songs: ExportSong[] };

export type ExportSong = {
  /** Its place in the part, from 1. */
  index: number;
  title: string;
  artist: string;
  /** 1 to MAX_ENERGY, or null. */
  energy: number | null;
  /** "120 BPM", or null. */
  tempo: string | null;
  /** In chord notation ("Em"): the band's key when it transposes, else the original. */
  key: string | null;
  /** "4:05": the band's own duration, else the original. */
  duration: string | null;
};

/** The texts an export writes, in each language. */
export const EXPORT_TEXTS: Record<
  Language,
  {
    part: (n: number) => string;
    songs: (count: number) => string;
    hoursMinutes: (hours: number, minutes: number) => string;
    minutes: (minutes: number) => string;
    withoutDuration: (count: number) => string;
    energy: (count: number) => string;
    footer: (date: string) => string;
  }
> = {
  en: {
    part: (n) => `Part ${n}`,
    songs: (count) => (count === 1 ? "1 song" : `${count} songs`),
    hoursMinutes: (hours, minutes) => `${hours} h ${minutes} min`,
    minutes: (minutes) => `${minutes} min`,
    withoutDuration: (count) =>
      count === 1 ? "1 song without a duration" : `${count} songs without a duration`,
    energy: (count) => `Energy ${count}`,
    footer: (date) => `Generated by ${APP_NAME} on ${date}`,
  },
  fr: {
    part: (n) => `Partie ${n}`,
    songs: (count) => (count <= 1 ? `${count} morceau` : `${count} morceaux`),
    hoursMinutes: (hours, minutes) => `${hours} h ${minutes} min`,
    minutes: (minutes) => `${minutes} min`,
    withoutDuration: (count) =>
      count === 1 ? "1 morceau sans durée" : `${count} morceaux sans durée`,
    energy: (count) => `Énergie ${count}`,
    footer: (date) => `Généré par ${APP_NAME} le ${date}`,
  },
};

type SourceSong = {
  title: string;
  artist: string;
  standardDuration: number | null;
  ownDuration: number | null;
  energy: number | null;
  tempo: number | null;
  key: MusicalKey | null;
  bandKey: MusicalKey | null;
};

export type ExportSource = {
  title: string;
  updatedAt: Date;
  band: { name: string; logoKey: string | null };
  parts: { name: string | null; songs: SourceSong[] }[];
};

export type ExportOptions = { language: Language; timeZone: string };

/** A date in words, in this language and time zone: "12 November 2026". */
export function exportDate(date: Date, { language, timeZone }: ExportOptions) {
  return new Intl.DateTimeFormat(language, { dateStyle: "long", timeZone }).format(date);
}

/** Whether this is a time zone the server knows ("Europe/Paris"). */
export function isTimeZone(value: string) {
  try {
    new Intl.DateTimeFormat("en", { timeZone: value });
    return true;
  } catch {
    return false;
  }
}

/** Songs' total duration in words, with those missing one; null without songs. */
function totalDuration(songs: readonly SourceSong[], language: Language) {
  if (songs.length === 0) return null;
  const texts = EXPORT_TEXTS[language];
  const { seconds, missing } = setlistDuration(songs);
  const { hours, minutes } = hoursAndMinutes(seconds);
  const total = hours > 0 ? texts.hoursMinutes(hours, minutes) : texts.minutes(minutes);
  return missing > 0 ? `${total} (${texts.withoutDuration(missing)})` : total;
}

/** What the export of this setlist shows. */
export function exportDocument(source: ExportSource, options: ExportOptions): ExportDocument {
  const { language } = options;
  const songs = source.parts.flatMap((part) => part.songs);
  return {
    language,
    title: source.title,
    songCount: EXPORT_TEXTS[language].songs(songs.length),
    duration: totalDuration(songs, language),
    band: source.band.name,
    date: exportDate(source.updatedAt, options),
    logoKey: source.band.logoKey,
    parts: source.parts.map((part, i) => ({
      name: part.name ?? EXPORT_TEXTS[language].part(i + 1),
      duration: totalDuration(part.songs, language),
      songs: part.songs.map((song, index) => {
        const key = song.bandKey ?? song.key;
        const duration = playedDuration(song);
        return {
          index: index + 1,
          title: song.title,
          artist: song.artist,
          energy: song.energy,
          tempo: song.tempo === null ? null : `${song.tempo} BPM`,
          key: key ? keyShort(key) : null,
          duration: duration === null ? null : formatDuration(duration),
        };
      }),
    })),
  };
}

/** What the main header says beside the band's name: "12 songs · 1 h 52 min". */
export function headerSummary(document: Pick<ExportDocument, "songCount" | "duration">) {
  return [document.songCount, document.duration].filter(Boolean).join(" · ");
}

/**
 * Raised when a renderer's output changes for the same document, so files made before are made
 * again: part of every fingerprint.
 */
export const RENDERER_VERSIONS: Record<SetlistExportFormat, number> = { pdf: 5, docx: 4 };

/** The hash of everything a file of this format would show: the same one, the same file. */
export function exportFingerprint(document: ExportDocument, format: SetlistExportFormat) {
  const hasher = new Bun.CryptoHasher("sha256");
  hasher.update(JSON.stringify({ format, renderer: RENDERER_VERSIONS[format], document }));
  return hasher.digest("hex");
}
