import { describe, expect, test } from "bun:test";
import JSZip from "jszip";
import sharp from "sharp";
import { logoSize, renderDocx } from "./docx";
import { exportDocument } from "./export-document";

const document = exportDocument(
  {
    title: "Wedding & party",
    updatedAt: new Date("2026-11-12T10:00:00Z"),
    band: { name: "The Covers", logoKey: null },
    parts: [
      {
        name: "Set 1",
        songs: [
          {
            title: "Rock",
            artist: "Band",
            standardDuration: 245,
            ownDuration: null,
            energy: 2,
            tempo: 96,
            key: "Em",
            bandKey: null,
          },
        ],
      },
      { name: null, songs: [] },
    ],
  },
  { language: "en", timeZone: "Europe/Paris" },
);

/** The text of a docx part, its XML tags removed. */
async function textOf(bytes: Uint8Array, path: string) {
  const zip = await JSZip.loadAsync(bytes);
  const xml = (await zip.file(path)?.async("string")) ?? "";
  return xml.replace(/<w:tab\/>/g, "\t").replace(/<[^>]+>/g, "");
}

describe("renderDocx", () => {
  test("the header, each part with its songs, the footer", async () => {
    const bytes = await renderDocx(document, { logo: null, generatedOn: "November 12, 2026" });
    const body = await textOf(bytes, "word/document.xml");
    expect(body).toContain("Wedding &amp; party\tNovember 12, 2026");
    expect(body).toContain("The Covers\t1 song · 4 min");
    expect(body).toContain("Set 1\t4 min");
    expect(body).toContain("1. Rock - Band - Energy 2 - 96 BPM - Em - 4:05");
    expect(body).toContain("Part 2");
    const zip = await JSZip.loadAsync(bytes);
    const footers = Object.keys(zip.files).filter((name) => /^word\/footer\d+\.xml$/.test(name));
    const footer = await Promise.all(footers.map((name) => textOf(bytes, name)));
    expect(footer.join("")).toContain("Generated by Coverband Beta on November 12, 2026");
  });

  test("with a logo: the image is in the file", async () => {
    const png = await sharp({
      create: { width: 400, height: 100, channels: 4, background: "#c00" },
    })
      .png()
      .toBuffer();
    const bytes = await renderDocx(document, {
      logo: { png: new Uint8Array(png), width: 400, height: 100 },
      generatedOn: "November 12, 2026",
    });
    const zip = await JSZip.loadAsync(bytes);
    expect(Object.keys(zip.files).some((name) => name.startsWith("word/media/"))).toBe(true);
  });
});

test("logoSize: fitted in its box, never enlarged", () => {
  const box = { width: 200, height: 100 };
  expect(logoSize({ width: 800, height: 200 }, box)).toEqual({ width: 200, height: 50 });
  expect(logoSize({ width: 300, height: 600 }, box)).toEqual({ width: 50, height: 100 });
  expect(logoSize({ width: 40, height: 20 }, box)).toEqual({ width: 40, height: 20 });
});
